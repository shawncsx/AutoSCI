"""AutoSCI — PDF export (v0.12).

Converts a paper.md (or an entire vault compilation) into a PDF.

Strategy:
    1. Try `weasyprint` first (best CSS / typography)
    2. Fall back to `reportlab` (pure Python, no native deps)
    3. If neither is installed, raise with a clear install hint

The PDF mirrors the v0.10 HTML report style but is print-friendly.
"""
from __future__ import annotations

import logging
import re
from pathlib import Path

from autosci.html_report import _md_to_html
from autosci.compilation import parse_paper_sections


log = logging.getLogger("autosci.pdf")


def _has_weasyprint() -> bool:
    try:
        import weasyprint  # type: ignore  # noqa: F401
        return True
    except Exception:
        return False


def _has_reportlab() -> bool:
    try:
        import reportlab  # type: ignore  # noqa: F401
        return True
    except Exception:
        return False


def _render_with_weasyprint(paper_md: str, title: str, verdict: str) -> bytes:
    from weasyprint import HTML
    body = _md_to_html(paper_md)
    html = f"""<!doctype html>
<html><head><meta charset="utf-8"><title>{title}</title>
<style>
  @page {{ size: A4; margin: 2cm; }}
  body {{ font-family: Georgia, "Times New Roman", serif; line-height: 1.55; color: #222; }}
  h1 {{ font-size: 22pt; border-bottom: 2px solid #444; padding-bottom: 6pt; }}
  h2 {{ font-size: 14pt; margin-top: 14pt; color: #1f3a93; }}
  pre {{ background: #f4f4f4; padding: 6pt; border-radius: 4pt; font-size: 9pt; }}
  code {{ background: #f4f4f4; padding: 1pt 3pt; border-radius: 2pt; font-size: 9pt; }}
  .cover {{ background: #f9fafb; border-left: 4px solid #16a34a; padding: 8pt 12pt; margin: 8pt 0; }}
  .verdict-kept {{ color: #16a34a; font-weight: bold; }}
  .verdict-revised {{ color: #ca8a04; font-weight: bold; }}
  .verdict-refuted {{ color: #dc2626; font-weight: bold; }}
  .meta {{ color: #6b7280; font-size: 9pt; }}
  .references ol {{ padding-left: 1.5em; }}
</style></head>
<body>
<h1>{title}</h1>
<div class="cover">
  <span class="verdict-{verdict}">Verdict: {verdict}</span>
  <div class="meta">Generated by AutoSCI v0.12 (reportlab/weasyprint).</div>
</div>
{body}
</body></html>"""
    return HTML(string=html).write_pdf()


def _render_with_reportlab(paper_md: str, title: str, verdict: str) -> bytes:
    """Pure-Python PDF via reportlab. Lower fidelity but no native deps."""
    from io import BytesIO
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import cm
    from reportlab.lib.colors import HexColor
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Preformatted

    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=2 * cm, rightMargin=2 * cm,
        topMargin=2 * cm, bottomMargin=2 * cm,
        title=title,
    )
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("H1", parent=styles["Heading1"], fontSize=20, spaceAfter=12)
    h2 = ParagraphStyle("H2", parent=styles["Heading2"], fontSize=13, spaceBefore=10, spaceAfter=4,
                        textColor=HexColor("#1f3a93"))
    body = ParagraphStyle("Body", parent=styles["BodyText"], fontSize=10, leading=14)
    verdict_colors = {"kept": "#16a34a", "revised": "#ca8a04", "refuted": "#dc2626"}
    vc = HexColor(verdict_colors.get(verdict, "#6b7280"))

    story = []
    story.append(Paragraph(title, h1))
    story.append(Paragraph(f'<font color="{vc.hexval()}"><b>Verdict: {verdict}</b></font>', body))
    story.append(Spacer(1, 8))

    sections = parse_paper_sections(paper_md)
    # Render Abstract as a quote first
    for sec, body_text in sections.items():
        if sec == "title":
            continue
        story.append(Paragraph(html_escape(sec), h2))
        # Block content
        if not body_text.strip():
            story.append(Paragraph("<i>(empty)</i>", body))
            continue
        for para in body_text.split("\n\n"):
            para = para.strip()
            if not para:
                continue
            if para.startswith("```"):
                # Fenced code — extract code lines
                code_lines = []
                for line in para.splitlines():
                    if line.strip().startswith("```"):
                        continue
                    code_lines.append(line)
                story.append(Preformatted("\n".join(code_lines), styles["Code"]))
            else:
                story.append(Paragraph(html_escape(para).replace("\n", "<br/>"), body))
        story.append(Spacer(1, 4))

    doc.build(story)
    return buf.getvalue()


def html_escape(s: str) -> str:
    return (s.replace("&", "&amp;")
             .replace("<", "&lt;")
             .replace(">", "&gt;"))


def export_pdf(
    paper_md_path: Path,
    out_pdf_path: Path,
    *,
    title_override: str | None = None,
    verdict: str = "pending",
) -> Path:
    """Convert a paper.md file to PDF.

    Tries weasyprint first, falls back to reportlab. The chosen backend
    is recorded in a sibling ``.pdf_backend`` file.
    """
    text = paper_md_path.read_text(encoding="utf-8", errors="replace")
    title = title_override or paper_md_path.parent.name
    out_pdf_path.parent.mkdir(parents=True, exist_ok=True)
    backend = "?"
    if _has_weasyprint():
        data = _render_with_weasyprint(text, title, verdict)
        backend = "weasyprint"
    elif _has_reportlab():
        data = _render_with_reportlab(text, title, verdict)
        backend = "reportlab"
    else:
        raise RuntimeError(
            "Neither weasyprint nor reportlab is installed. "
            "Install one: `pip install weasyprint` or `pip install reportlab`."
        )
    out_pdf_path.write_bytes(data)
    out_pdf_path.with_suffix(".pdf_backend").write_text(backend + "\n", encoding="utf-8")
    log.info("wrote %s (via %s, %d bytes)", out_pdf_path, backend, len(data))
    return out_pdf_path


def export_compilation(
    vault_dir: Path, out_pdf_path: Path, *, kept_only: bool = True
) -> Path:
    """Render a multi-paper compilation (vault/kept/*) to a single PDF."""
    from autosci.compilation import build_compilation_markdown
    md = build_compilation_markdown(vault_dir, kept_only=kept_only)
    out_pdf_path.parent.mkdir(parents=True, exist_ok=True)
    if _has_weasyprint():
        data = _render_with_weasyprint(md, f"AutoSCI Compilation ({vault_dir.name})", "kept")
        backend = "weasyprint"
    elif _has_reportlab():
        data = _render_with_reportlab(md, f"AutoSCI Compilation ({vault_dir.name})", "kept")
        backend = "reportlab"
    else:
        raise RuntimeError("Install weasyprint or reportlab for PDF export.")
    out_pdf_path.write_bytes(data)
    out_pdf_path.with_suffix(".pdf_backend").write_text(backend + "\n", encoding="utf-8")
    return out_pdf_path
